#!/bin/bash
set -e

OUT_DIR="$1"
AIRCRAFT="$2"
TIME_SEC="$3"
TRIM_BOOL="$4"
SENSOR_BOOL="$5"
CONTROL_BOOL="$6"
VERBOSE_BOOL="$7"
DATA_BOOL="$8"
PLOT_BOOL="$9"
TEST_BOOL="${10}"
QUICK_BOOL="${11}"

OUT_PATH="data/$OUT_DIR/args.txt"
mkdir -p "$(dirname "$OUT_PATH")"

cat > "$OUT_PATH" <<EOF
AIRCRAFT=$AIRCRAFT
TIME_SEC=$TIME_SEC
TRIM_BOOL=$TRIM_BOOL
SENSOR_BOOL=$SENSOR_BOOL
CONTROL_BOOL=$CONTROL_BOOL
VERBOSE_BOOL=$VERBOSE_BOOL
DATA_BOOL=$DATA_BOOL
PLOT_BOOL=$PLOT_BOOL
TEST_BOOL=$TEST_BOOL
QUICK_BOOL=$QUICK_BOOL
OUT_DIR=$OUT_DIR
EOF

echo "File saved successfully to $OUT_PATH"
